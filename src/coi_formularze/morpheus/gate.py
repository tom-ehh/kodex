"""Wake light gate (wake.md §4): lint, replay of the affected section, gate-form smoke test.

- **Lint:** schema/size (the `Skill` model), the P0 PII scan, a non-empty trigger, and
  trigger breadth against the gate forms' labels (`gate_labels.json`, generated by
  tools/make_gate_labels.py): a trigger matching too many gate labels is refused.
- **Replay:** the episode's section re-drafted from the DocCache with the candidate
  loaded (medium tier model); the field must pass its validator and match the
  worker's correction. Expired document -> `unreplayed`.
- **Smoke:** gate-form sections whose labels match the trigger (at most `SMOKE_MAX`),
  drafted without and with the candidate; no new failures allowed. Needs the gate
  forms' markdown (`COI_MORPHEUS_GATE_MD_DIR`, `<slug>.md` or `md-<slug>.md`); skipped
  without it.
"""

import json
from dataclasses import dataclass, field
from functools import lru_cache
from importlib.resources import files
from pathlib import Path

from coi_formularze.morpheus.match import SectionTarget, score
from coi_formularze.morpheus.models import Skill
from coi_formularze.morpheus.replay import SectionRef, find_field, replay_section
from coi_formularze.morpheus.sanitize import pii_findings

BREADTH_MAX = 0.15  # share of gate labels a trigger may match
SMOKE_MAX = 2


@lru_cache(maxsize=1)
def gate_forms() -> dict[str, list[dict]]:
    return json.loads(files("coi_formularze.morpheus").joinpath("gate_labels.json").read_text("utf-8"))


def _matches(skill: Skill, label: str, validation: list[str]) -> bool:
    return score(skill, SectionTarget.of([label], validation)) > 0


@dataclass
class Lint:
    ok: bool
    reasons: list[str] = field(default_factory=list)
    breadth: float = 0.0


def lint(skill: Skill) -> Lint:
    reasons: list[str] = []
    if pii := pii_findings(skill.model_dump(mode="json")):
        reasons.append("pii: " + ", ".join(p.split(": ")[-1] for p in pii))
    t = skill.trigger
    if not (t.labels_any or t.regex or t.validator):
        reasons.append("empty trigger")
    if not (skill.prompt_snippet or skill.validator_rule):
        reasons.append("skill does nothing")
    labels = [(f["label"], f["validation"]) for secs in gate_forms().values()
              for s in secs for f in s["fields"]]
    hit = sum(_matches(skill, lb, v) for lb, v in labels)
    breadth = hit / len(labels) if labels else 0.0
    if breadth > BREADTH_MAX:
        reasons.append(f"trigger too broad: {hit}/{len(labels)} gate labels")
    return Lint(ok=not reasons, reasons=reasons, breadth=round(breadth, 3))


def smoke_sections(skill: Skill) -> list[tuple[str, dict]]:
    out = []
    for slug, secs in gate_forms().items():
        for s in secs:
            if any(_matches(skill, f["label"], f["validation"]) for f in s["fields"]):
                out.append((slug, s))
    return out[:SMOKE_MAX]


def _acc(fields: list[dict], expected: list[dict]) -> float:
    if not expected:
        return 1.0
    good = 0
    for e in expected:
        f = find_field(fields, e["label"])
        good += f is not None and set(f.get("validation") or []) == set(e["validation"])
    return good / len(expected)


def _gate_md(md_dir: str | None, slug: str) -> str | None:
    if not md_dir:
        return None
    for name in (f"{slug}.md", f"md-{slug}.md"):
        p = Path(md_dir) / name
        if p.is_file():
            return p.read_text("utf-8")
    return None


async def smoke(chat, model: str, candidate: Skill, base: list[Skill], md_dir: str | None,
                max_per_section: int = 5) -> dict:
    """No new failures on matching gate sections. {'status': pass|fail|skipped, ...}."""
    secs = smoke_sections(candidate)
    if not secs:
        return {"status": "pass", "sections": 0, "note": "no gate section matches"}
    rows, cost, lat = [], 0.0, 0.0
    for slug, s in secs:
        md = _gate_md(md_dir, slug)
        if md is None:
            continue
        ref = SectionRef("", s["title"])
        before = await replay_section(chat, model, md, ref, base, max_per_section)
        after = await replay_section(chat, model, md, ref, [*base, candidate], max_per_section)
        cost += before.cost + after.cost
        lat += before.latency_s + after.latency_s
        a0 = _acc(before.fields, s["fields"]) if before.ok else 0.0
        a1 = _acc(after.fields, s["fields"]) if after.ok else 0.0
        rows.append({"form": slug, "section": s["title"], "ok_before": before.ok,
                     "ok_after": after.ok, "acc_before": round(a0, 3), "acc_after": round(a1, 3)})
    if not rows:
        return {"status": "skipped", "sections": len(secs), "note": "gate markdown unavailable"}
    failed = [r for r in rows if (r["ok_before"] and not r["ok_after"]) or r["acc_after"] < r["acc_before"]]
    return {"status": "fail" if failed else "pass", "sections": len(rows), "rows": rows,
            "cost": round(cost, 6), "latency_s": round(lat, 2)}
